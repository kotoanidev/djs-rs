use compact_str::CompactString;
use serde::{Deserialize, Serialize};

use crate::{
    id::{ChannelId, GuildId, MessageId, WebhookId},
    macros::int_enum,
    user::User,
    util::Timestamp,
};

/// A message sent in a channel.
///
/// **Coverage:** this is the Phase 1 subset of the
/// [message object](https://docs.discord.com/developers/resources/message#message-object).
/// Unknown fields are ignored during deserialization, so newer payloads always parse.
///
/// discord.js counterpart: `Message`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Message {
    /// The message's ID.
    pub id: MessageId,
    /// The ID of the channel the message was sent in.
    pub channel_id: ChannelId,
    /// The ID of the guild the message was sent in.
    ///
    /// Only present on messages received through the gateway in guild channels; REST responses
    /// do not include it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub guild_id: Option<GuildId>,
    /// The author of the message.
    ///
    /// For webhook messages this is a pseudo-user built from the webhook's ID, name and avatar.
    pub author: User,
    /// The text content of the message.
    ///
    /// Empty unless the bot has the `MESSAGE_CONTENT` privileged intent, the message mentions
    /// the bot, or the message is a DM.
    pub content: CompactString,
    /// When the message was sent.
    pub timestamp: Timestamp,
    /// When the message was last edited, if ever.
    pub edited_timestamp: Option<Timestamp>,
    /// Whether this was a text-to-speech message.
    pub tts: bool,
    /// Whether the message mentions `@everyone` (or `@here`).
    pub mention_everyone: bool,
    /// Whether the message is pinned.
    pub pinned: bool,
    /// The kind of message.
    #[serde(rename = "type")]
    pub kind: MessageType,
    /// If the message was generated by a webhook, the webhook's ID.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub webhook_id: Option<WebhookId>,
    /// The message this message replies to or forwards, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub message_reference: Option<MessageReference>,
}

/// A reference from one message to another: a reply or a forward.
///
/// See the [message reference object](https://docs.discord.com/developers/resources/message#message-reference-object).
///
/// discord.js counterpart: `MessageReference` / `Message#reference`.
///
/// # Examples
///
/// Referencing a message to reply to it:
///
/// ```
/// use djs_model::{id::MessageId, message::MessageReference};
///
/// let reply = MessageReference::reply(MessageId::new(1_300_000_000_000_000_000));
/// assert_eq!(
///     serde_json::to_string(&reply).unwrap(),
///     r#"{"type":0,"message_id":"1300000000000000000"}"#
/// );
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct MessageReference {
    /// The kind of reference. Defaults to [`MessageReferenceType::Default`] (a reply) when
    /// absent.
    #[serde(rename = "type", default)]
    pub kind: MessageReferenceType,
    /// The ID of the referenced message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub message_id: Option<MessageId>,
    /// The ID of the referenced message's channel.
    ///
    /// Optional when sending a reply, required when forwarding, always present when received.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub channel_id: Option<ChannelId>,
    /// The ID of the referenced message's guild.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub guild_id: Option<GuildId>,
    /// When sending: whether to fail if the referenced message does not exist (Discord's default
    /// is `true`) instead of sending a normal, non-reply message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fail_if_not_exists: Option<bool>,
}

impl MessageReference {
    /// Creates a reference that replies to `message_id` in the same channel.
    #[must_use]
    pub const fn reply(message_id: MessageId) -> Self {
        Self {
            kind: MessageReferenceType::Default,
            message_id: Some(message_id),
            channel_id: None,
            guild_id: None,
            fail_if_not_exists: None,
        }
    }
}

int_enum! {
    /// The [type of a message reference](https://docs.discord.com/developers/resources/message#message-reference-types).
    #[derive(Default)]
    pub enum MessageReferenceType: u8 {
        /// A standard reference used by replies (`referenced_message` is populated).
        #[default]
        Default = 0,
        /// A reference used to forward a message at a point in time (`message_snapshots` is
        /// populated).
        Forward = 1,
    }
}

int_enum! {
    /// The [type of a message](https://docs.discord.com/developers/resources/message#message-object-message-types).
    ///
    /// discord.js counterpart: `MessageType` (re-exported from discord-api-types).
    pub enum MessageType: u8 {
        /// A regular message.
        Default = 0,
        /// A recipient was added to a group DM.
        RecipientAdd = 1,
        /// A recipient was removed from a group DM.
        RecipientRemove = 2,
        /// A call was started.
        Call = 3,
        /// A channel's name was changed.
        ChannelNameChange = 4,
        /// A channel's icon was changed.
        ChannelIconChange = 5,
        /// A message was pinned.
        ChannelPinnedMessage = 6,
        /// A member joined the guild.
        UserJoin = 7,
        /// A member boosted the guild.
        GuildBoost = 8,
        /// A boost brought the guild to tier 1.
        GuildBoostTier1 = 9,
        /// A boost brought the guild to tier 2.
        GuildBoostTier2 = 10,
        /// A boost brought the guild to tier 3.
        GuildBoostTier3 = 11,
        /// A channel follow (announcement channel subscription) was added.
        ChannelFollowAdd = 12,
        /// The guild was disqualified from Server Discovery.
        GuildDiscoveryDisqualified = 14,
        /// The guild was requalified for Server Discovery.
        GuildDiscoveryRequalified = 15,
        /// Initial warning of the Server Discovery grace period.
        GuildDiscoveryGracePeriodInitialWarning = 16,
        /// Final warning of the Server Discovery grace period.
        GuildDiscoveryGracePeriodFinalWarning = 17,
        /// A thread was created from a message.
        ThreadCreated = 18,
        /// A reply to another message.
        Reply = 19,
        /// The response to a slash (chat input) command.
        ChatInputCommand = 20,
        /// The first message of a thread, referencing the message the thread was started from.
        ThreadStarterMessage = 21,
        /// A reminder to invite people to the guild.
        GuildInviteReminder = 22,
        /// The response to a context menu command.
        ContextMenuCommand = 23,
        /// An auto moderation action was taken.
        AutoModerationAction = 24,
        /// A role subscription was purchased.
        RoleSubscriptionPurchase = 25,
        /// An upsell for a premium interaction.
        InteractionPremiumUpsell = 26,
        /// A stage started.
        StageStart = 27,
        /// A stage ended.
        StageEnd = 28,
        /// A member became a stage speaker.
        StageSpeaker = 29,
        /// A member raised their hand on a stage.
        ///
        /// Not listed in the official documentation; present in discord-api-types.
        StageRaiseHand = 30,
        /// A stage's topic was changed.
        StageTopic = 31,
        /// A guild application premium subscription was purchased.
        GuildApplicationPremiumSubscription = 32,
        /// Incident alert mode (raid protection) was enabled.
        GuildIncidentAlertModeEnabled = 36,
        /// Incident alert mode (raid protection) was disabled.
        GuildIncidentAlertModeDisabled = 37,
        /// A raid was reported.
        GuildIncidentReportRaid = 38,
        /// A raid report was marked as a false alarm.
        GuildIncidentReportFalseAlarm = 39,
        /// A purchase notification.
        PurchaseNotification = 44,
        /// The results of a poll.
        PollResult = 46,
    }
}

impl MessageType {
    /// Returns `true` if messages of this type can be deleted.
    ///
    /// Based on the "Deletable" column of the Discord documentation. Unknown types are assumed to
    /// be deletable. `AutoModerationAction` messages additionally require the `MANAGE_MESSAGES`
    /// permission.
    #[must_use]
    pub const fn is_deletable(self) -> bool {
        !matches!(
            self,
            Self::RecipientAdd
                | Self::RecipientRemove
                | Self::Call
                | Self::ChannelNameChange
                | Self::ChannelIconChange
                | Self::ThreadStarterMessage
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn message_type_forward_compatible() {
        assert_eq!(MessageType::from(19), MessageType::Reply);
        assert_eq!(MessageType::from(250), MessageType::Unknown(250));
        assert!(MessageType::from(250).is_unknown());
        assert!(!MessageType::Reply.is_unknown());
        // `Unknown` holding a known value is equal to the named variant.
        assert_eq!(MessageType::Unknown(0), MessageType::Default);
        assert!(!MessageType::Unknown(0).is_unknown());
        assert_eq!(serde_json::to_string(&MessageType::Reply).unwrap(), "19");
    }
}
