impl MessageType {
    /// Returns `true` if messages of this type can be deleted.
    ///
    /// Based on the "Deletable" column of the Discord documentation. Unknown types are assumed to
    /// be deletable. `AutoModerationAction` messages additionally require the `MANAGE_MESSAGES`
    /// permission.
    #[must_use]
    pub const fn is_deletable(self) -> bool {
        !matches!(
            self,
            Self::RecipientAdd
                | Self::RecipientRemove
                | Self::Call
                | Self::ChannelNameChange
                | Self::ChannelIconChange
                | Self::ThreadStarterMessage
        )
    }
}

