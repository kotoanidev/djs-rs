/// [Which mentions of a message notify](https://docs.discord.com/developers/resources/message#allowed-mentions-object)
/// their targets, when sending.
///
/// Mentions are always rendered; this only controls the notifications. The
/// [default](Self::default) (everything empty) notifies nobody. When the field is absent from a
/// request, Discord notifies every mention in regular messages, and only users in interaction
/// responses and webhook messages.
///
/// The permissions still apply: roles notify only if they are mentionable or the bot has
