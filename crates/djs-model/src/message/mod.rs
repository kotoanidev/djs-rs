/// A [message](https://docs.discord.com/developers/resources/message#message-object) sent in a
/// channel.
///
/// The same type is used for messages received through the gateway (`MESSAGE_CREATE`,
/// `MESSAGE_UPDATE`) and from REST. The gateway adds a few fields ([`guild_id`](Self::guild_id),
/// [`member`](Self::member), the members of [`mentions`](Self::mentions),
/// [`channel_type`](Self::channel_type)) that REST responses do not have.
///
/// Without the `MESSAGE_CONTENT` privileged intent, [`content`](Self::content),
/// [`embeds`](Self::embeds) and [`attachments`](Self::attachments) are empty and
/// [`poll`](Self::poll) is absent, except in DMs, in messages that mention the bot and in the
/// bot's own messages.
///
/// Rare sub-objects are boxed so a typical message stays small (D-054). The `resolved` data is
/// added with the interactions step (D-062).
///
/// Contains floats (through [`Attachment`]), so it is `PartialEq` but not `Eq` (D-064).
///
/// discord.js counterpart: `Message`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct Message {
    /// The message's ID.
    pub id: MessageId,
    /// The ID of the channel the message was sent in.
    pub channel_id: ChannelId,
    /// The ID of the guild the message was sent in (gateway only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub guild_id: Option<GuildId>,
    /// The author of the message.
    ///
    /// For webhook messages this is a pseudo-user built from the webhook's ID, name and avatar
    /// (check [`webhook_id`](Self::webhook_id)).
    pub author: User,
    /// The author's member in the guild (gateway only, guild messages not sent by webhooks).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub member: Option<Box<PartialMember>>,
    /// The text content of the message.
    ///
    /// Empty without the `MESSAGE_CONTENT` privileged intent (see above).
    pub content: CompactString,
    /// When the message was sent.
    pub timestamp: Timestamp,
    /// When the message was last edited, if ever.
    pub edited_timestamp: Option<Timestamp>,
    /// Whether this was a text-to-speech message (always `false` in `MESSAGE_UPDATE`).
    pub tts: bool,
    /// Whether the message mentions `@everyone` (or `@here`).
    pub mention_everyone: bool,
    /// The users mentioned in the message, with their members in guild messages received
    /// through the gateway (D-060).
    #[serde(default)]
    pub mentions: Vec<Mention>,
    /// The roles mentioned in the message.
    #[serde(default)]
    pub mention_roles: Vec<RoleId>,
    /// The channels mentioned in the message. Only channels visible to everyone in public
    /// guilds are listed, and currently only on crossposted messages.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub mention_channels: Vec<ChannelMention>,
    /// The attached files (except those referenced in embeds or components).
    #[serde(default)]
    pub attachments: Vec<Attachment>,
    /// The embeds.
    #[serde(default)]
    pub embeds: Vec<Embed>,
    /// The reactions.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reactions: Vec<Reaction>,
    /// The value the sender used to check that the message was sent.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub nonce: Option<Nonce>,
    /// Whether the message is pinned.
    pub pinned: bool,
    /// If the message was generated by a webhook, the webhook's ID.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub webhook_id: Option<WebhookId>,
    /// The kind of message.
    #[serde(rename = "type")]
    pub kind: MessageType,
    /// The Rich Presence activity of a Rich Presence chat embed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub activity: Option<Box<MessageActivity>>,
    /// The application of a Rich Presence chat embed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub application: Option<Box<PartialApplication>>,
    /// The application of an interaction response or an application-owned webhook message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub application_id: Option<ApplicationId>,
    /// The message's flags.
    #[serde(default)]
    pub flags: MessageFlags,
    /// The source of a crosspost, channel follow, pin, reply, forward, … (see
    /// [`MessageReference`]).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub message_reference: Option<MessageReference>,
    /// The forwarded message(s), when [`message_reference`](Self::message_reference) is a
    /// [forward](MessageReferenceType::Forward).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub message_snapshots: Vec<MessageSnapshot>,
    /// The message this one replies to (or starts a thread from, or a context menu command was
    /// run on), for messages of type [`Reply`](MessageType::Reply),
    /// [`ThreadStarterMessage`](MessageType::ThreadStarterMessage) and
    /// [`ContextMenuCommand`](MessageType::ContextMenuCommand) (D-061).
    #[serde(default, skip_serializing_if = "ReferencedMessage::is_not_fetched")]
    pub referenced_message: ReferencedMessage,
    /// The interaction the message was sent for.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub interaction_metadata: Option<Box<InteractionMetadata>>,
    /// The interaction the message responds to. **Deprecated** by Discord in favor of
    /// [`interaction_metadata`](Self::interaction_metadata).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub interaction: Option<Box<MessageInteraction>>,
    /// The components (buttons, select menus, or Components V2 layout with
    /// [`IS_COMPONENTS_V2`](MessageFlags::IS_COMPONENTS_V2)). Empty without the
    /// `MESSAGE_CONTENT` privileged intent (see above).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub components: Vec<Component>,
    /// The thread started from this message (with the current user's thread member, if any).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub thread: Option<Box<Channel>>,
    /// The stickers sent with the message.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub sticker_items: Vec<StickerItem>,
    /// The full stickers sent with the message. **Deprecated** by Discord in favor of
    /// [`sticker_items`](Self::sticker_items).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub stickers: Vec<Sticker>,
    /// The approximate position of the message in its thread: a generally increasing number
    /// (with possible gaps and duplicates) for messages in threads.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub position: Option<u32>,
    /// The role subscription purchase or renewal a
    /// [`RoleSubscriptionPurchase`](MessageType::RoleSubscriptionPurchase) message announces.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub role_subscription_data: Option<Box<RoleSubscriptionData>>,
    /// The poll.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub poll: Option<Box<Poll>>,
    /// The call a [`Call`](MessageType::Call) message is about.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub call: Option<Box<MessageCall>>,
    /// A client theme shared through the message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub shared_client_theme: Option<Box<SharedClientTheme>>,
    /// The type of the channel the message was sent in (gateway only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub channel_type: Option<ChannelType>,
}

/// A user mentioned in a [`Message`] (D-060).
///
/// In guild messages received through the gateway, Discord adds the mentioned user's
/// [`member`](Self::member). `Mention` dereferences to its [`User`], so `mention.id` works.
///
/// discord.js counterpart: `MessageMentions#users` / `MessageMentions#members`.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct Mention {
    /// The mentioned user.
    pub user: User,
    /// The user's member in the guild (gateway only).
    pub member: Option<Box<PartialMember>>,
}

impl Mention {
    /// Creates a mention of `user` without member data.
    #[must_use]
    pub const fn new(user: User) -> Self {
        Self { user, member: None }
    }
}

impl Deref for Mention {
    type Target = User;

    fn deref(&self) -> &User {
        &self.user
    }
}

impl From<User> for Mention {
    fn from(user: User) -> Self {
        Self::new(user)
    }
}

/// The fields of a [`User`] plus `member`, decoded in one pass (D-060). Must list the same
/// fields with the same serde attributes as [`User`]; `tests::mention_decodes_like_user` checks
/// that.
#[derive(Deserialize)]
struct RawMention {
    id: UserId,
    username: CompactString,
    #[serde(with = "crate::user::discriminator")]
    discriminator: u16,
    global_name: Option<CompactString>,
    avatar: Option<ImageHash>,
    #[serde(default)]
    bot: bool,
    #[serde(default)]
    system: bool,
    #[serde(default)]
    banner: Option<ImageHash>,
    #[serde(default)]
    accent_color: Option<u32>,
    #[serde(default)]
    public_flags: Option<UserFlags>,
    #[serde(default)]
    avatar_decoration_data: Option<Box<AvatarDecorationData>>,
    #[serde(default)]
    collectibles: Option<Box<Collectibles>>,
    #[serde(default)]
    primary_guild: Option<Box<PrimaryGuild>>,
    #[serde(default)]
    member: Option<Box<PartialMember>>,
}

impl<'de> Deserialize<'de> for Mention {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let raw = RawMention::deserialize(deserializer)?;
        Ok(Self {
            user: User {
                id: raw.id,
                username: raw.username,
                discriminator: raw.discriminator,
                global_name: raw.global_name,
                avatar: raw.avatar,
                bot: raw.bot,
                system: raw.system,
                banner: raw.banner,
                accent_color: raw.accent_color,
                public_flags: raw.public_flags,
                avatar_decoration_data: raw.avatar_decoration_data,
                collectibles: raw.collectibles,
                primary_guild: raw.primary_guild,
            },
            member: raw.member,
        })
    }
}

impl Serialize for Mention {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        #[derive(Serialize)]
        struct Flat<'a> {
            #[serde(flatten)]
            user: &'a User,
            #[serde(skip_serializing_if = "Option::is_none")]
            member: Option<&'a PartialMember>,
        }

        Flat {
            user: &self.user,
            member: self.member.as_deref(),
        }
        .serialize(serializer)
    }
}

/// The message a reply (or thread starter, or context menu command message) refers to (D-061).
///
/// Discord distinguishes an absent field ("did not try to fetch it") from `null` ("it was
/// deleted"); this type keeps that distinction.
#[derive(Clone, Debug, Default, PartialEq)]
#[non_exhaustive]
pub enum ReferencedMessage {
    /// The field was absent: Discord did not try to fetch the message, so its state is unknown
    /// (also the case for messages of other types).
    #[default]
    NotFetched,
    /// The field was `null`: the referenced message was deleted.
    Deleted,
    /// The referenced message.
    Message(Box<Message>),
}

impl ReferencedMessage {
    /// Returns the referenced message, if Discord sent it.
    #[must_use]
    pub fn as_message(&self) -> Option<&Message> {
        match self {
            Self::Message(message) => Some(message),
            Self::NotFetched | Self::Deleted => None,
        }
    }

    /// Converts into the referenced message, if Discord sent it.
    #[must_use]
    pub fn into_message(self) -> Option<Box<Message>> {
        match self {
            Self::Message(message) => Some(message),
            Self::NotFetched | Self::Deleted => None,
        }
    }

    /// Whether the field was absent (the state of the referenced message is unknown).
    #[must_use]
    pub const fn is_not_fetched(&self) -> bool {
        matches!(self, Self::NotFetched)
    }

    /// Whether the referenced message was deleted.
    #[must_use]
    pub const fn is_deleted(&self) -> bool {
        matches!(self, Self::Deleted)
    }
}

impl Serialize for ReferencedMessage {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        // `NotFetched` is skipped by `Message`; on its own it is written as `null` too.
        match self {
            Self::Message(message) => message.serialize(serializer),
            Self::NotFetched | Self::Deleted => serializer.serialize_none(),
        }
    }
}

impl<'de> Deserialize<'de> for ReferencedMessage {
    /// Reads `null` as [`Deleted`](Self::Deleted) and an object as the message. An absent field
    /// becomes [`NotFetched`](Self::NotFetched) through `#[serde(default)]`.
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Ok(match Option::<Box<Message>>::deserialize(deserializer)? {
            Some(message) => Self::Message(message),
            None => Self::Deleted,
        })
    }
}

/// The [nonce](https://docs.discord.com/developers/resources/message#message-object) a sender
/// attached to a message: an integer or a string (up to 25 characters).
///
/// Integers outside the `i64` range are kept as their decimal text in [`Nonce::String`].
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum Nonce {
    /// An integer nonce.
    Integer(i64),
    /// A string nonce.
    String(CompactString),
}

impl Serialize for Nonce {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        match self {
            Self::Integer(value) => serializer.serialize_i64(*value),
            Self::String(value) => serializer.serialize_str(value),
        }
    }
}

impl<'de> Deserialize<'de> for Nonce {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct NonceVisitor;

        impl Visitor<'_> for NonceVisitor {
            type Value = Nonce;

            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("an integer or string nonce")
            }

            fn visit_i64<E: DeError>(self, value: i64) -> Result<Nonce, E> {
                Ok(Nonce::Integer(value))
            }

            fn visit_u64<E: DeError>(self, value: u64) -> Result<Nonce, E> {
                Ok(i64::try_from(value).map_or_else(
                    |_| Nonce::String(compact_str::format_compact!("{value}")),
                    Nonce::Integer,
                ))
            }

            fn visit_str<E: DeError>(self, value: &str) -> Result<Nonce, E> {
                Ok(Nonce::String(value.into()))
            }
        }

        deserializer.deserialize_any(NonceVisitor)
    }
}

/// A reference from one message to another: a reply or a forward.
///
/// See the [message reference object](https://docs.discord.com/developers/resources/message#message-reference-object).
///
/// discord.js counterpart: `MessageReference` / `Message#reference`.
///
/// # Examples
///
/// Referencing a message to reply to it:
///
/// ```
/// use djs_model::{id::MessageId, message::MessageReference};
///
/// let reply = MessageReference::reply(MessageId::new(1_300_000_000_000_000_000));
/// assert_eq!(
///     serde_json::to_string(&reply).unwrap(),
///     r#"{"type":0,"message_id":"1300000000000000000"}"#
/// );
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[non_exhaustive]
pub struct MessageReference {
    /// The kind of reference. Defaults to [`MessageReferenceType::Default`] (a reply) when
    /// absent.
    #[serde(rename = "type", default)]
    pub kind: MessageReferenceType,
    /// The ID of the referenced message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub message_id: Option<MessageId>,
    /// The ID of the referenced message's channel.
    ///
    /// Optional when sending a reply, required when forwarding, always present when received.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub channel_id: Option<ChannelId>,
    /// The ID of the referenced message's guild.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub guild_id: Option<GuildId>,
    /// When sending: whether to fail if the referenced message does not exist (Discord's default
    /// is `true`) instead of sending a normal, non-reply message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fail_if_not_exists: Option<bool>,
}

impl MessageReference {
    /// Creates a reference that replies to `message_id` in the same channel.
    #[must_use]
    pub const fn reply(message_id: MessageId) -> Self {
        Self {
            kind: MessageReferenceType::Default,
            message_id: Some(message_id),
            channel_id: None,
            guild_id: None,
            fail_if_not_exists: None,
        }
    }
}

