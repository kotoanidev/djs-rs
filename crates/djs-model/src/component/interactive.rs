/// A [button](https://docs.discord.com/developers/components/reference#button), in an
/// [action row](super::ActionRow) or as a [section](super::Section) accessory (messages only).
///
/// Its `style` decides which fields it has (D-066). Link and premium buttons do not send an
/// interaction when clicked.
///
/// discord.js counterpart: `ButtonComponent` / `ButtonBuilder`.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
#[doc(alias = "ButtonComponent")]
pub enum Button {
    /// A button with a `custom_id` that sends an interaction (styles 1-4).
    Interactive(InteractiveButton),
    /// A button that opens a URL (style 5).
    Link(LinkButton),
    /// A button that opens the purchase of an SKU (style 6).
    Premium(PremiumButton),
    /// A button style this version of the library does not know about (boxed: it keeps every
    /// button field).
    Unknown(Box<UnknownButton>),
}

impl Button {
    /// Returns the component's numeric identifier, if set.
    #[must_use]
    pub const fn id(&self) -> Option<i32> {
        match self {
            Self::Interactive(button) => button.id,
            Self::Link(button) => button.id,
            Self::Premium(button) => button.id,
            Self::Unknown(button) => button.id,
        }
    }

    /// Returns the button's style.
    #[must_use]
    pub const fn style(&self) -> ButtonStyle {
        match self {
            Self::Interactive(button) => button.style,
            Self::Link(_) => ButtonStyle::Link,
            Self::Premium(_) => ButtonStyle::Premium,
            Self::Unknown(button) => button.style,
        }
    }

    /// Returns the developer-defined identifier of an interactive button.
    #[must_use]
    pub fn custom_id(&self) -> Option<&str> {
        match self {
            Self::Interactive(button) => Some(&button.custom_id),
            Self::Unknown(button) => button.custom_id.as_deref(),
            Self::Link(_) | Self::Premium(_) => None,
        }
    }

    /// Whether the button is disabled.
    #[must_use]
    pub const fn disabled(&self) -> bool {
        match self {
            Self::Interactive(button) => button.disabled,
            Self::Link(button) => button.disabled,
            Self::Premium(button) => button.disabled,
            Self::Unknown(button) => button.disabled,
        }
    }
}

/// Serializes a button variant together with its `style`.
#[derive(Serialize)]
struct Styled<'a, T> {
    style: ButtonStyle,
    #[serde(flatten)]
    button: &'a T,
}

impl Serialize for Button {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let style = self.style();
        match self {
            Self::Interactive(button) => Styled { style, button }.serialize(serializer),
            Self::Link(button) => Styled { style, button }.serialize(serializer),
            Self::Premium(button) => Styled { style, button }.serialize(serializer),
            Self::Unknown(button) => Styled { style, button }.serialize(serializer),
        }
    }
}

/// A button that sends an interaction with its [`custom_id`](Self::custom_id) when clicked
/// (styles [`Primary`](ButtonStyle::Primary) to [`Danger`](ButtonStyle::Danger)).
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[non_exhaustive]
pub struct InteractiveButton {
    /// The component's numeric identifier (generated by Discord when not set).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub id: Option<i32>,
    /// The style: one of `Primary`, `Secondary`, `Success`, `Danger`.
    #[serde(skip)]
    pub style: ButtonStyle,
    /// The developer-defined identifier (1-100 characters).
    pub custom_id: CompactString,
    /// The text on the button (max 80 characters).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub label: Option<CompactString>,
    /// The emoji on the button.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub emoji: Option<PartialEmoji>,
    /// Whether the button is disabled.
    #[serde(skip_serializing_if = "core::ops::Not::not")]
    pub disabled: bool,
}

impl InteractiveButton {
    /// Creates an enabled button without label or emoji (set at least one before sending).
    #[must_use]
    pub fn new(style: ButtonStyle, custom_id: impl Into<CompactString>) -> Self {
        Self {
            id: None,
            style,
            custom_id: custom_id.into(),
            label: None,
            emoji: None,
            disabled: false,
        }
    }
}

